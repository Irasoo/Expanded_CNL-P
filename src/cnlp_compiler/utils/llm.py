# These 429 codes describe account or budget state rather than temporary
# request pressure. Repeating the same request cannot repair them.
_NON_RETRYABLE_RATE_LIMIT_MARKERS = {
    "credit_balance_exhausted",
    "insufficient_quota",
    "organization_spend_limit_exceeded",
    "organization_usage_limit_exceeded",
    "project_spend_limit_exceeded",
}

_RequestResult = TypeVar("_RequestResult")


class LLMRequestError(RuntimeError):
    """Base error for one compiler-time model request."""


class RetryableLLMRequestError(LLMRequestError):
    """The request still failed after local retries due to a transient fault.

    RQ4 uses this explicit type to decide whether the *whole compilation*
    should be attempted again. It must not infer retryability from localized
    exception text.
    """


class NonRetryableLLMRequestError(LLMRequestError):
    """The request failed for a condition that repeating cannot repair."""


class PromptSection(TypedDict):
    """One role-tagged section sent to a model."""

    role: Role
    content: str


class WebSource(TypedDict):
    """One URL returned by a web-search response."""

    title: str | None
    url: str


class WebSearchResult(TypedDict):
    """The answer and source metadata returned by web search."""

    answer: str
    citations: list[WebSource]
    sources: list[WebSource]
    response_id: str | None
    model: str | None
    usage: dict[str, Any] | None


class TokenUsageValues(TypedDict):
    """Normalized token counters shared by both OpenAI API surfaces."""

    # All tokens supplied to the model for the request.
    input_tokens: int
    # The cached portion of input_tokens; it must not be added again.
    cached_input_tokens: int
    # All tokens generated by the model for the request.
    output_tokens: int
    # The reasoning portion of output_tokens; it must not be added again.
    reasoning_tokens: int
    # Total reported by the service, normally input_tokens + output_tokens.
    total_tokens: int


class LLMRequestUsage(TypedDict):
    """Usage record for one compiler-time model request."""

    # Identifies whether Chat Completions or Responses web search was used.
    request_type: LLMRequestType
    # Records the requested model so later experiments remain auditable.
    model: str
    # Distinguishes a returned response from a request that raised an error.
    status: LLMRequestStatus
    # None means that the service returned no token-usage information.
    usage: TokenUsageValues | None


class CompilationTokenUsageReport(TypedDict):
    """Detached snapshot of model usage for exactly one compile call."""

    # Number of compiler-time model requests, including failed requests.
    request_count: int
    # Number of model requests for which a response was returned.
    successful_request_count: int
    # Number of model requests that raised before returning a response.
    failed_request_count: int
    # Successful responses for which the provider omitted usage data.
    requests_without_usage_count: int
    # Sum of every request that supplied usage data.
    total: TokenUsageValues
    # Per-request details retained for later experimental inspection.
    calls: list[LLMRequestUsage]


def _empty_token_usage() -> TokenUsageValues:
    return {
        "input_tokens": 0,
        "cached_input_tokens": 0,
        "output_tokens": 0,
        "reasoning_tokens": 0,
        "total_tokens": 0,
    }


class CompilationTokenUsageSession:
    """Collect token usage produced inside one compiler invocation."""

    def __init__(self) -> None:
        self._calls: list[LLMRequestUsage] = []
        self._started_request_count = 0
    def wait_for_request_slot(
        self,
        request_delay_seconds: float,
    ) -> None:
        """Delay every compiler request after the first one."""
        if request_delay_seconds <= 0:
            return
        if self._started_request_count > 0:
            time.sleep(request_delay_seconds)

    def begin_request(self) -> int:
        """Reserve the sequence number shown for one compiler-time request."""
        self._started_request_count += 1
        return self._started_request_count

    def record_success(
        self,
        *,
        request_type: LLMRequestType,
        model: str,
        usage: TokenUsageValues | None,
    ) -> None:
        self._calls.append(
            {
                "request_type": request_type,
                "model": model,
                "status": "succeeded",
                "usage": dict(usage) if usage is not None else None,
            }
        )

    def record_failure(
        self,
        *,
        request_type: LLMRequestType,
        model: str,
    ) -> None:
        self._calls.append(
            {
                "request_type": request_type,
                "model": model,
                "status": "failed",
                "usage": None,
            }
        )

    def snapshot(self) -> CompilationTokenUsageReport:
        """Return a detached report that later sessions cannot mutate."""
        total = _empty_token_usage()
        successful_request_count = 0
        failed_request_count = 0
        requests_without_usage_count = 0
        calls: list[LLMRequestUsage] = []

        for call in self._calls:
            usage = call["usage"]
            copied_call: LLMRequestUsage = {
                "request_type": call["request_type"],
                "model": call["model"],
                "status": call["status"],
                "usage": dict(usage) if usage is not None else None,
            }
            calls.append(copied_call)

            if call["status"] == "failed":
                failed_request_count += 1
                continue

            successful_request_count += 1
            if usage is None:
                requests_without_usage_count += 1
                continue

            for field_name in total:
                total[field_name] += usage[field_name]

        return {
            "request_count": len(calls),
            "successful_request_count": successful_request_count,
            "failed_request_count": failed_request_count,
            "requests_without_usage_count": requests_without_usage_count,
            "total": total,
            "calls": calls,
        }


# ContextVar binds the active collector to the current compile execution
# context. It is deliberately not a process-wide cumulative singleton: every
# CNLPCompiler.compile() installs a new session and restores the old context
# afterwards, so sequential and asynchronous compilations do not mix usage.
_ACTIVE_COMPILATION_USAGE: ContextVar[
    CompilationTokenUsageSession | None
] = ContextVar(
    "active_cnlp_compilation_token_usage",
    default=None,
)


@contextmanager
def track_compilation_token_usage(
) -> Iterator[CompilationTokenUsageSession]:
    """Activate an isolated usage session for one compile call."""
    session = CompilationTokenUsageSession()
    context_token: Token[CompilationTokenUsageSession | None] = (
        _ACTIVE_COMPILATION_USAGE.set(session)
    )
    try:
        yield session
    finally:
        # reset() is required even when compilation raises. Without it, model
        # requests made after a failed compile could leak into its report.
        _ACTIVE_COMPILATION_USAGE.reset(context_token)


def _record_successful_request(
    *,
    request_type: LLMRequestType,
    model: str,
    usage: TokenUsageValues | None,
) -> None:
    session = _ACTIVE_COMPILATION_USAGE.get()
    if session is not None:
        session.record_success(
            request_type=request_type,
            model=model,
            usage=usage,
        )


def _record_failed_request(
    *,
    request_type: LLMRequestType,
    model: str,
) -> None:
    session = _ACTIVE_COMPILATION_USAGE.get()
    if session is not None:
        session.record_failure(
            request_type=request_type,
            model=model,
        )


def _announce_request_start(
    *,
    request_type: LLMRequestType,
    model: str,
) -> tuple[int | None, float]:
    """Print progress only while a compiler token session is active."""
    started_at = time.monotonic()
    session = _ACTIVE_COMPILATION_USAGE.get()
    if session is None:
        return None, started_at

    request_index = session.begin_request()
    print(
        f"[Compiler][LLM] Request {request_index} started: "
        f"{request_type}, model={model}",
        flush=True,
    )
    return request_index, started_at


def _wait_for_compilation_request_slot(
    request_delay_seconds: float,
) -> None:
    """Apply one compilation-wide delay before every request after the first."""
    session = _ACTIVE_COMPILATION_USAGE.get()
    if session is not None:
        session.wait_for_request_slot(request_delay_seconds)


def _announce_request_result(
    *,
    request_index: int | None,
    started_at: float,
    status: LLMRequestStatus,
    usage: TokenUsageValues | None,
) -> None:
    if request_index is None:
        return

    duration = time.monotonic() - started_at
    if status == "failed":
        usage_text = "usage unavailable"
    elif usage is None:
        usage_text = "provider returned no usage"
    else:
        usage_text = (
            f"input={usage['input_tokens']}, "
            f"output={usage['output_tokens']}, "
            f"total={usage['total_tokens']}"
        )
    print(
        f"[Compiler][LLM] Request {request_index} {status} "
        f"in {duration:.2f}s: {usage_text}",
        flush=True,
    )


