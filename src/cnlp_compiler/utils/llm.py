def create_prompt_section(role: Role, content: str) -> PromptSection:
    return {
        "role": role,
        "content": content,
    }


def _normalize_chat_prompt(
    prompt: str | list[PromptSection],
) -> list[PromptSection]:
    if isinstance(prompt, str):
        return [create_prompt_section("user", prompt)]
    return prompt


def _read_usage_value(source: Any, field_name: str) -> Any:
    """Read one SDK usage field from either an object or a dictionary."""
    if source is None:
        return None
    if isinstance(source, dict):
        return source.get(field_name)
    return getattr(source, field_name, None)


def _read_token_count(source: Any, field_name: str) -> int:
    value = _read_usage_value(source, field_name)
    if isinstance(value, int) and not isinstance(value, bool) and value >= 0:
        return value
    return 0


def _normalize_chat_completion_usage(usage: Any) -> TokenUsageValues | None:
    """Translate Chat Completions usage names into the compiler format."""
    if usage is None:
        return None

    prompt_details = _read_usage_value(
        usage,
        "prompt_tokens_details",
    )
    completion_details = _read_usage_value(
        usage,
        "completion_tokens_details",
    )
    return {
        "input_tokens": _read_token_count(usage, "prompt_tokens"),
        "cached_input_tokens": _read_token_count(
            prompt_details,
            "cached_tokens",
        ),
        "output_tokens": _read_token_count(usage, "completion_tokens"),
        "reasoning_tokens": _read_token_count(
            completion_details,
            "reasoning_tokens",
        ),
        "total_tokens": _read_token_count(usage, "total_tokens"),
    }


def _normalize_responses_usage(usage: Any) -> TokenUsageValues | None:
    """Translate Responses API usage into the compiler format."""
    if usage is None:
        return None

    input_details = _read_usage_value(usage, "input_tokens_details")
    output_details = _read_usage_value(usage, "output_tokens_details")
    return {
        "input_tokens": _read_token_count(usage, "input_tokens"),
        "cached_input_tokens": _read_token_count(
            input_details,
            "cached_tokens",
        ),
        "output_tokens": _read_token_count(usage, "output_tokens"),
        "reasoning_tokens": _read_token_count(
            output_details,
            "reasoning_tokens",
        ),
        "total_tokens": _read_token_count(usage, "total_tokens"),
    }


def _append_unique_source(
    target: list[WebSource],
    *,
    title: Any,
    url: Any,
) -> None:
    if not isinstance(url, str) or not url.strip():
        return

    normalized_url = url.strip()
    if any(source["url"] == normalized_url for source in target):
        return

    target.append(
        {
            "title": (
                title.strip()
                if isinstance(title, str) and title.strip()
                else None
            ),
            "url": normalized_url,
        }
    )


def extract_web_search_result(response: Any) -> WebSearchResult:
    """Extract answer text, citations, and complete sources from a response."""

    if hasattr(response, "model_dump"):
        data = response.model_dump(mode="json")
    elif isinstance(response, dict):
        data = response
    else:
        raise TypeError(
            "Cannot parse web-search response with type "
            f"{type(response).__name__!r}."
        )

    answer = getattr(response, "output_text", None)
    if not isinstance(answer, str):
        answer = ""

    citations: list[WebSource] = []
    sources: list[WebSource] = []
    fallback_answer_parts: list[str] = []
    output_items = data.get("output", [])
    if not isinstance(output_items, list):
        output_items = []

    for item in output_items:
        if not isinstance(item, dict):
            continue

        if item.get("type") == "web_search_call":
            action = item.get("action")
            if not isinstance(action, dict):
                continue
            raw_sources = action.get("sources", [])
            if not isinstance(raw_sources, list):
                continue
            for source in raw_sources:
                if isinstance(source, dict):
                    _append_unique_source(
                        sources,
                        title=source.get("title"),
                        url=source.get("url"),
                    )
            continue

        if item.get("type") != "message":
            continue
        contents = item.get("content", [])
        if not isinstance(contents, list):
            continue
        for content in contents:
            if (
                not isinstance(content, dict)
                or content.get("type") != "output_text"
            ):
                continue

            text = content.get("text")
            if isinstance(text, str):
                fallback_answer_parts.append(text)

            annotations = content.get("annotations", [])
            if not isinstance(annotations, list):
                continue
            for annotation in annotations:
                if (
                    isinstance(annotation, dict)
                    and annotation.get("type") == "url_citation"
                ):
                    _append_unique_source(
                        citations,
                        title=annotation.get("title"),
                        url=annotation.get("url"),
                    )

    if not answer:
        answer = "\n".join(fallback_answer_parts)

    usage = data.get("usage")
    if not isinstance(usage, dict):
        usage = None

    return {
        "answer": answer,
        "citations": citations,
        "sources": sources,
        "response_id": (
            data.get("id") if isinstance(data.get("id"), str) else None
        ),
        "model": (
            data.get("model")
            if isinstance(data.get("model"), str)
            else None
        ),
        "usage": usage,
    }


def _api_error_markers(exc: Exception) -> set[str]:
    """Extract stable error code/type markers from an SDK API error."""
    markers: set[str] = set()
    body = getattr(exc, "body", None)
    candidate_mappings: list[dict[str, Any]] = []
    if isinstance(body, dict):
        candidate_mappings.append(body)
        nested_error = body.get("error")
        if isinstance(nested_error, dict):
            candidate_mappings.append(nested_error)

    for mapping in candidate_mappings:
        for field_name in ("code", "type"):
            value = mapping.get(field_name)
            if isinstance(value, str) and value.strip():
                markers.add(value.strip().lower())
    return markers


def _is_retryable_request_error(exc: Exception) -> bool:
    """Return whether retrying the same model request can plausibly recover."""
    # APITimeoutError is an APIConnectionError subclass in the OpenAI SDK, so
    # this covers both timeouts and lower-level network/connection failures.
    if isinstance(exc, APIConnectionError):
        return True
    if not isinstance(exc, APIStatusError):
        return False

    status_code = exc.status_code
    if status_code in {408, 409} or status_code >= 500:
        return True
    if status_code != 429:
        return False

    # A 429 can mean temporary request pressure or a permanent balance/spend
    # limit. Only the former should be retried.
    return not bool(
        _api_error_markers(exc) & _NON_RETRYABLE_RATE_LIMIT_MARKERS
    )


def _retry_after_seconds(exc: Exception) -> float | None:
    """Read numeric Retry-After headers returned by the provider or relay."""
    response = getattr(exc, "response", None)
    headers = getattr(response, "headers", None)
    if headers is None:
        return None

    retry_after_ms = headers.get("retry-after-ms")
    if retry_after_ms is not None:
        try:
            return max(float(retry_after_ms) / 1000.0, 0.0)
        except (TypeError, ValueError):
            pass

    retry_after = headers.get("retry-after")
    if retry_after is None:
        return None
    try:
        return max(float(retry_after), 0.0)
    except (TypeError, ValueError):
        # HTTP-date Retry-After values are uncommon for the API and cannot be
        # safely interpreted without a trusted current server clock. Fall back
        # to the configured retry delay instead.
        return None


class OpenaiClient(LLMclient, WebSearchClient):
    api_key: str
    model: str
    org: str
    base_url: str
    reasoning_effort: ReasoningEffort | None
    request_delay_seconds: float
    request_timeout_seconds: float
    request_max_retries: int
    request_retry_delay_seconds: float

    def __init__(
        self,
        api_key: str,
        model: str,
        org: str,
        base_url: str,
        reasoning_effort: str | None = None,
        request_delay_seconds: float | str | None = None,
        request_timeout_seconds: float | str | None = None,
        request_max_retries: int | str | None = None,
        request_retry_delay_seconds: float | str | None = None,
    ) -> None:
        self.api_key = api_key.strip()
        self.model = model.strip()
        self.org = org.strip()
        self.base_url = base_url.rstrip("/")
        self.reasoning_effort = self._resolve_reasoning_effort(
            reasoning_effort
        )
        self.request_delay_seconds = self._resolve_request_delay(
            request_delay_seconds
        )
        self.request_timeout_seconds = self._resolve_positive_float(
            configured_value=request_timeout_seconds,
            environment_name="OPENAI_REQUEST_TIMEOUT_SECONDS",
            default=600.0,
        )
        self.request_max_retries = self._resolve_non_negative_integer(
            configured_value=request_max_retries,
            environment_name="OPENAI_REQUEST_MAX_RETRIES",
            default=5,
        )
        self.request_retry_delay_seconds = (
            self._resolve_non_negative_float(
                configured_value=request_retry_delay_seconds,
                environment_name="OPENAI_REQUEST_RETRY_DELAY_SECONDS",
                default=5.0,
            )
        )

    @staticmethod
    def _resolve_reasoning_effort(
        configured_value: str | None,
    ) -> ReasoningEffort | None:
        raw_value = (
            configured_value
            if configured_value is not None
            else get_env_value("OPENAI_REASONING_EFFORT")
        )
        if raw_value is None or not raw_value.strip():
            return None

        normalized_value = raw_value.strip().lower()
        if normalized_value not in _REASONING_EFFORT_VALUES:
            raise ValueError(
                "OPENAI_REASONING_EFFORT must be one of: "
                + ", ".join(sorted(_REASONING_EFFORT_VALUES))
            )
        return cast(ReasoningEffort, normalized_value)

    @staticmethod
    def _resolve_request_delay(
        configured_value: float | str | None,
    ) -> float:
        raw_value: float | str | None = configured_value
        if raw_value is None:
            raw_value = get_env_value(
                "OPENAI_REQUEST_DELAY_SECONDS"
            )
        if raw_value is None or (
            isinstance(raw_value, str) and not raw_value.strip()
        ):
            return 0.0

        try:
            interval = float(raw_value)
        except (TypeError, ValueError) as exc:
            raise ValueError(
                "OPENAI_REQUEST_DELAY_SECONDS must be a non-negative "
                "number."
            ) from exc
        if interval < 0:
            raise ValueError(
                "OPENAI_REQUEST_DELAY_SECONDS must be a non-negative "
                "number."
            )
        return interval

    @staticmethod
    def _resolve_non_negative_float(
        *,
        configured_value: float | str | None,
        environment_name: str,
        default: float,
    ) -> float:
        raw_value: float | str | None = configured_value
        if raw_value is None:
            raw_value = get_env_value(environment_name)
        if raw_value is None or (
            isinstance(raw_value, str) and not raw_value.strip()
        ):
            return default

        try:
            value = float(raw_value)
        except (TypeError, ValueError) as exc:
            raise ValueError(
                f"{environment_name} must be a non-negative number."
            ) from exc
        if value < 0:
            raise ValueError(
                f"{environment_name} must be a non-negative number."
            )
        return value

    @classmethod
    def _resolve_positive_float(
        cls,
        *,
        configured_value: float | str | None,
        environment_name: str,
        default: float,
    ) -> float:
        value = cls._resolve_non_negative_float(
            configured_value=configured_value,
            environment_name=environment_name,
            default=default,
        )
        if value <= 0:
            raise ValueError(
                f"{environment_name} must be a positive number."
            )
        return value

    @staticmethod
    def _resolve_non_negative_integer(
        *,
        configured_value: int | str | None,
        environment_name: str,
        default: int,
    ) -> int:
        raw_value: int | str | None = configured_value
        if raw_value is None:
            raw_value = get_env_value(environment_name)
        if raw_value is None or (
            isinstance(raw_value, str) and not raw_value.strip()
        ):
            return default

        if isinstance(raw_value, bool):
            raise ValueError(
                f"{environment_name} must be a non-negative integer."
            )
        try:
            value = int(raw_value)
        except (TypeError, ValueError) as exc:
            raise ValueError(
                f"{environment_name} must be a non-negative integer."
            ) from exc
        if value < 0 or str(value) != str(raw_value).strip():
            raise ValueError(
                f"{environment_name} must be a non-negative integer."
            )
        return value

    def _create_sdk_client(self) -> OpenAI:
        client_arguments: dict[str, Any] = {
            "api_key": self.api_key,
            "base_url": self.base_url,
            # Retry behavior is implemented explicitly below so the configured
            # five retries cannot multiply with the SDK's hidden defaults.
            "max_retries": 0,
            "timeout": self.request_timeout_seconds,
        }
        if self.org:
            client_arguments["organization"] = self.org
        return OpenAI(**client_arguments)

    def _request_with_retry(
        self,
        *,
        request_index: int | None,
        operation: str,
        request_call: Callable[[], _RequestResult],
    ) -> _RequestResult:
        """Run one logical request with bounded transient-failure retries."""
        maximum_attempts = self.request_max_retries + 1
        for attempt_index in range(1, maximum_attempts + 1):
            try:
                return request_call()
            except Exception as exc:
                should_retry = (
                    _is_retryable_request_error(exc)
                    and attempt_index < maximum_attempts
                )
                if not should_retry:
                    raise

                provider_delay = _retry_after_seconds(exc)
                retry_delay = max(
                    self.request_retry_delay_seconds,
                    provider_delay or 0.0,
                )
                if request_index is not None:
                    print(
                        f"[Compiler][LLM] Request {request_index} "
                        f"attempt {attempt_index}/{maximum_attempts} "
                        f"failed with {type(exc).__name__}; retrying in "
                        f"{retry_delay:g}s.",
                        flush=True,
                    )
                time.sleep(retry_delay)

        # The loop either returns a result or re-raises its last exception.
        raise AssertionError(f"Unreachable request loop: {operation}")

    def _build_runtime_error(
        self,
        *,
        operation: str,
        exc: Exception,
        requested_model: str,
    ) -> LLMRequestError:
        error_type: type[LLMRequestError] = (
            RetryableLLMRequestError
            if _is_retryable_request_error(exc)
            else NonRetryableLLMRequestError
        )
        return error_type(
            "LLM request failed. "
            f"operation={operation}; "
            f"error_type={type(exc).__name__}; "
            f"error={exc}; "
            f"cwd={Path.cwd()}; "
            f"env_path_hint={Path.cwd() / '.env'}; "
            f"api_key_present={bool(self.api_key)}; "
            f"api_key_length={len(self.api_key)}; "
            f"model={requested_model!r}; "
            f"base_url={self.base_url!r}"
        )

    def complete(
        self,
        prompt: str | list[PromptSection],
        specified_model: str | None = None,
    ) -> str:
        requested_model = (
            self.model if specified_model is None else specified_model
        )
        _wait_for_compilation_request_slot(
            self.request_delay_seconds
        )
        request_index, started_at = _announce_request_start(
            request_type="chat_completion",
            model=requested_model,
        )
        request: dict[str, Any] = {
            "model": requested_model,
            "n": 1,
            "temperature": 0,
            "messages": _normalize_chat_prompt(prompt),
        }
        if self.reasoning_effort is not None:
            request["reasoning_effort"] = self.reasoning_effort
        sdk_client = self._create_sdk_client()
        try:
            completion = self._request_with_retry(
                request_index=request_index,
                operation="chat_completion",
                request_call=lambda: (
                    sdk_client.chat.completions.create(**request)
                ),
            )
        except Exception as exc:
            # A failed request has no reliable token count, but retaining the
            # failed attempt makes the compilation report complete.
            _record_failed_request(
                request_type="chat_completion",
                model=requested_model,
            )
            _announce_request_result(
                request_index=request_index,
                started_at=started_at,
                status="failed",
                usage=None,
            )
            raise self._build_runtime_error(
                operation="chat_completion",
                exc=exc,
                requested_model=requested_model,
            ) from exc

        # Recording happens in the shared ContextVar session rather than on
        # this client instance. Clients created by different compiler stages
        # therefore contribute to the same current-compilation report.
        normalized_usage = _normalize_chat_completion_usage(
            _read_usage_value(completion, "usage")
        )
        _record_successful_request(
            request_type="chat_completion",
            model=requested_model,
            usage=normalized_usage,
        )
        _announce_request_result(
            request_index=request_index,
            started_at=started_at,
            status="succeeded",
            usage=normalized_usage,
        )
        return completion.choices[0].message.content or ""

    def search_web(
        self,
        prompt: str | list[PromptSection],
        specified_model: str | None = None,
        search_context_size: SearchContextSize = "medium",
        force_search: bool = True,
    ) -> WebSearchResult:
        if search_context_size not in {"low", "medium", "high"}:
            raise ValueError(
                "search_context_size must be 'low', 'medium', or 'high'."
            )

        requested_model = (
            self.model if specified_model is None else specified_model
        )
        _wait_for_compilation_request_slot(
            self.request_delay_seconds
        )
        request_index, started_at = _announce_request_start(
            request_type="web_search",
            model=requested_model,
        )
        request: dict[str, Any] = {
            "model": requested_model,
            "tools": [
                {
                    "type": "web_search",
                    "search_context_size": search_context_size,
                }
            ],
            "tool_choice": "required" if force_search else "auto",
            "include": ["web_search_call.action.sources"],
            "input": prompt,
        }
        if self.reasoning_effort is not None:
            request["reasoning"] = {
                "effort": self.reasoning_effort,
            }
        sdk_client = self._create_sdk_client()
        try:
            response = self._request_with_retry(
                request_index=request_index,
                operation="web_search",
                request_call=lambda: sdk_client.responses.create(
                    **request
                ),
            )
        except Exception as exc:
            _record_failed_request(
                request_type="web_search",
                model=requested_model,
            )
            _announce_request_result(
                request_index=request_index,
                started_at=started_at,
                status="failed",
                usage=None,
            )
            raise self._build_runtime_error(
                operation="web_search",
                exc=exc,
                requested_model=requested_model,
            ) from exc

        normalized_usage = _normalize_responses_usage(
            _read_usage_value(response, "usage")
        )
        _record_successful_request(
            request_type="web_search",
            model=requested_model,
            usage=normalized_usage,
        )
        _announce_request_result(
            request_index=request_index,
            started_at=started_at,
            status="succeeded",
            usage=normalized_usage,
        )
        return extract_web_search_result(response)


def create_llm_client() -> LLMclient:
    return create_openai_client()


def create_web_search_client() -> WebSearchClient:
    return create_openai_client()


def create_openai_client() -> OpenaiClient:
    return OpenaiClient(
        api_key=get_env_value("OPENAI_API_KEY") or "",
        model=get_env_value("OPENAI_MODEL") or "",
        org=get_env_value("OPENAI_ORG") or "",
        base_url=get_env_value("BASE_URL") or "",
    )


def get_model_response(
    messages: str | list[PromptSection],
    specified_model: str | None = None,
) -> str:
    return create_llm_client().complete(
        messages,
        specified_model=specified_model,
    )


def get_web_search_response(
    messages: str | list[PromptSection],
    specified_model: str | None = None,
    search_context_size: SearchContextSize = "medium",
    force_search: bool = True,
) -> WebSearchResult:
    return create_web_search_client().search_web(
        prompt=messages,
        specified_model=specified_model,
        search_context_size=search_context_size,
        force_search=force_search,
    )
